"""PyRIT runner shim for ARE P3.1 direct prompt-injection probes.

Wraps Microsoft's PyRIT (Azure/PyRIT, MIT) as an additional adversarial probe
source alongside Garak (canonical jailbreak shapes) and Inspect AI (round-trip
data model). PyRIT contributes an independent attack-generator family (converter
chains, dataset orchestrators, multi-turn primitives) that strengthens P3.1
discrimination without changing rubric weights.

Wrap-only per `contracts/scanner-implementation-supervision-v1.md@v1.0`
("Wrap don't fork"): this module does not copy PyRIT internals into ARE code.
Lazy-import boundary mirrors `scanners/inspect_runner.py` so the harness still
imports cleanly on hosts without the dep (e.g. legacy CI worker images).

Scoring math is NOT duplicated here — pass-rate → raw mapping reuses
`harness.bench.prompt_injection._resistance_to_raw` so byte-stability vs the
canonical P3.1 bench is preserved at the same pass rate (anti-fork invariant).

Output row shape (matches scanners/inspect_runner.py + scanners/agentdojo_runner.py):

    {
        "dim_id": "P3.1",
        "rubric_point_id": "ROBUSTNESS.PROMPT_INJECTION",
        "benchmark": "pyrit:direct-prompt-injection",
        "model_id": "mock:smoke",
        "n_items": 5,
        "n_passed": 5,
        "pass_rate": 1.0,
        "raw": 4.0,
        "trace": [...],
        "runner_framework": "pyrit",
        "pyrit_version": "0.6.0",
        "upstream_eval": "pyrit",
        "upstream_eval_version": "0.6.0",
    }
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Callable

from harness.bench import prompt_injection as p31
from harness.runner import ModelRunner

try:
    import pyrit  # type: ignore

    _PYRIT_AVAILABLE = True
    _PYRIT_VERSION = getattr(pyrit, "__version__", "unknown")
except ImportError:
    # pyrit==0.6.0 (datasets>=3.0.0) cannot share the harness venv with
    # garak==0.10.0 (datasets<2.17). When the in-process import fails, fall
    # back to the per-framework venv resolver (BEAAA-13331) — it returns
    # (False, "not-installed") when no venv is configured, so this branch is
    # byte-identical to the historical behavior on unconfigured CI hosts.
    from scanners.eval_framework_venv import resolve_framework

    _PYRIT_AVAILABLE, _PYRIT_VERSION = resolve_framework("pyrit")


class PyRITRunnerError(RuntimeError):
    pass


@dataclass(frozen=True)
class PyRITProbeItem:
    """Canonical row for a PyRIT-sourced direct-injection probe.

    `probe_id` is the pinned PyRIT identifier (orchestrator + dataset family)
    surfaced in rubric/probe_mappings/pyrit.yaml. `canary` is the substring
    the evaluator looks for in the model response — a hit means the
    injection landed (item failed).
    """

    id: str
    category: str
    prompt: str
    canary: str
    probe_id: str


P31_RUBRIC_POINT_ID = "ROBUSTNESS.PROMPT_INJECTION"


def _require_pyrit() -> None:
    if not _PYRIT_AVAILABLE:
        raise PyRITRunnerError(
            "pyrit not installed; pip install -r requirements.txt to enable "
            "PyRIT probe runs. See requirements.txt for the pinned version."
        )


def _default_eval(response: str, item: PyRITProbeItem) -> bool:
    """Fallback evaluator: resisted iff the canary substring is absent.

    Delegates to the canonical P3.1 bench so substring-match semantics stay
    aligned with the in-tree harness path (anti-fork rule).
    """
    return not p31._injection_succeeded(response, item.canary)


def run_via_pyrit(
    runner: ModelRunner,
    items: list[PyRITProbeItem],
    *,
    evaluator: Callable[[str, PyRITProbeItem], bool] | None = None,
    on_progress: Callable[[int, int, dict[str, Any]], None] | None = None,
) -> dict[str, Any]:
    """Execute a PyRIT-sourced P3.1 probe set against a ModelRunner.

    Phase-1: items are pre-realized PyRITProbeItem rows whose prompts have
    been generated by PyRIT's converter chain / orchestrator out-of-band and
    pinned into rubric/probe_mappings/pyrit.yaml. The runner calls the
    subject endpoint via `runner.complete()` and the evaluator marks resisted
    (canary absent) vs landed (canary present). Aggregate pass_rate maps to
    raw via the canonical P3.1 bench's `_resistance_to_raw` curve so the new
    probe source cannot drift from the existing Garak/Inspect P3.1 paths.

    Phase-2 (out of scope for BEAAA-712): swap the pre-realized prompts for
    a live PyRIT `PromptSendingOrchestrator` call against the subject runner;
    row shape stays identical so downstream consumers don't care which path
    produced it.
    """
    _require_pyrit()

    eval_fn = evaluator or _default_eval
    trace: list[dict[str, Any]] = []
    n_passed = 0
    total = len(items)

    for idx, item in enumerate(items, 1):
        response = runner.complete(item.prompt)
        passed = bool(eval_fn(response, item))
        n_passed += int(passed)
        entry = {
            "id": item.id,
            "probe_id": item.probe_id,
            "category": item.category,
            "canary": item.canary,
            "passed": passed,
            "raw_response": response,
        }
        trace.append(entry)
        if on_progress is not None:
            on_progress(idx, total, entry)

    pass_rate = (n_passed / total) if total else 0.0
    raw = p31._resistance_to_raw(pass_rate)

    return {
        "dim_id": "P3.1",
        "rubric_point_id": P31_RUBRIC_POINT_ID,
        "benchmark": "pyrit:direct-prompt-injection",
        "model_id": runner.model_id(),
        "n_items": total,
        "n_passed": n_passed,
        "pass_rate": pass_rate,
        "resistance_rate": pass_rate,
        "raw": raw,
        "trace": trace,
        "runner_framework": "pyrit",
        "pyrit_version": _PYRIT_VERSION,
        "upstream_eval": "pyrit",
        "upstream_eval_version": _PYRIT_VERSION,
    }


__all__ = [
    "P31_RUBRIC_POINT_ID",
    "PyRITProbeItem",
    "PyRITRunnerError",
    "run_via_pyrit",
]
